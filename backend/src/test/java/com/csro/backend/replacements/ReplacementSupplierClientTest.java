package com.csro.backend.replacements;

import static org.junit.jupiter.api.Assertions.*;
import static org.springframework.test.web.client.match.MockRestRequestMatchers.*;
import static org.springframework.test.web.client.response.MockRestResponseCreators.*;

import java.net.SocketTimeoutException;
import java.time.LocalDate;
import java.time.OffsetDateTime;
import java.util.List;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.http.HttpMethod;
import org.springframework.http.MediaType;
import org.springframework.test.json.JsonCompareMode;
import org.springframework.test.web.client.MockRestServiceServer;
import org.springframework.transaction.support.TransactionSynchronizationManager;
import org.springframework.web.client.RestClient;

import com.csro.backend.replacements.ReplacementSupplierClient.FrozenRequest;
import com.csro.backend.replacements.ReplacementSupplierClient.Stay;
import com.csro.backend.replacements.ReplacementSupplierException.Kind;

/** API-029/030 boundary tests. No business DB and no supplier retries are involved. */
class ReplacementSupplierClientTest {
    private static final String BASE = "http://127.0.0.1:8001";
    private static final String CREATE = BASE + "/mock-supplier/v1/replacement-bookings";
    private static final String LOOKUP = BASE + "/mock-supplier/v1/replacement-booking-requests/BRQ-001";
    private static final String TOKEN = "replacement-client-unit-only";
    private static final FrozenRequest REQUEST = new FrozenRequest("BRQ-001", "QUOTE-A", "HOTEL-A",
            new Stay(LocalDate.of(2026, 11, 10), LocalDate.of(2026, 11, 13), 2, 1),
            480000L, "KRW", "GUEST-001");
    // Independently transcribed source-contract examples, not generated by the Mock code.
    private static final String CONFIRMED = """
            {"requestId":"BRQ-001","status":"CONFIRMED","supplierBookingId":"ALT-001",
             "quoteId":"QUOTE-A","propertyId":"HOTEL-A",
             "confirmedPrice":{"totalAmount":480000,"currency":"KRW"},
             "confirmedAt":"2026-11-09T10:22:00+09:00"}
            """;
    private static final String CREATED = CONFIRMED.replace("\"confirmedPrice\"", """
            "stay":{"checkInDate":"2026-11-10","checkOutDate":"2026-11-13","adults":2,"rooms":1},
            "confirmedPrice"
            """);
    private static final String PROCESSING = """
            {"requestId":"BRQ-001","status":"PROCESSING","supplierBookingId":null,
             "quoteId":"QUOTE-A","propertyId":"HOTEL-A","confirmedPrice":null,"confirmedAt":null}
            """;
    private static final String FAILED = PROCESSING.replace("PROCESSING", "FAILED").replace("\"confirmedAt\":null", """
            "confirmedAt":null,"failureCode":"PRICE_CHANGED","failedAt":"2026-11-09T10:22:00+09:00",
            "currentTotalAmount":498000,"currency":"KRW"
            """);

    private RestClient http;
    private MockRestServiceServer server;
    private ReplacementSupplierClient supplier;

    @BeforeEach
    void setup() {
        var builder = RestClient.builder().baseUrl(BASE);
        server = MockRestServiceServer.bindTo(builder).build();
        http = builder.build(); supplier = new ReplacementSupplierClient(http, TOKEN);
    }

    @AfterEach
    void noHiddenRetries() {
        TransactionSynchronizationManager.setActualTransactionActive(false);
        server.verify();
    }

    @Test
    void sendsOnlyTheFrozenFourFieldBodyAndStableKeyThenReadsTheSameRequestWithoutPosting() {
        server.expect(requestTo(CREATE)).andExpect(method(HttpMethod.POST))
                .andExpect(header("Authorization", "Bearer " + TOKEN))
                .andExpect(header("Idempotency-Key", "BRQ-001"))
                .andExpect(content().json("""
                        {"quoteId":"QUOTE-A","expectedTotalAmount":480000,"currency":"KRW","guestReference":"GUEST-001"}
                        """, JsonCompareMode.STRICT))
                .andRespond(withRawStatus(201).contentType(MediaType.APPLICATION_JSON).body(CREATED));
        server.expect(requestTo(LOOKUP)).andExpect(method(HttpMethod.GET))
                .andExpect(header("Authorization", "Bearer " + TOKEN))
                .andRespond(withSuccess(CONFIRMED, MediaType.APPLICATION_JSON));
        var created = supplier.create(REQUEST);
        var read = supplier.lookup(REQUEST);
        assertEquals("CONFIRMED", created.status()); assertEquals("ALT-001", created.supplierBookingId());
        assertEquals(480000L, created.confirmedAmount());
        assertEquals(OffsetDateTime.parse("2026-11-09T10:22:00+09:00"), read.confirmedAt());
        assertEquals(CONFIRMED, read.rawJson());
    }

    @Test
    void wrongRequestQuotePriceAndStayCannotConfirmTheLocalSelection() {
        List<String> replies = List.of(CREATED.replace("BRQ-001", "BRQ-other"),
                CREATED.replace("QUOTE-A", "QUOTE-other"), CREATED.replace("HOTEL-A", "HOTEL-other"),
                CREATED.replace("\"totalAmount\":480000", "\"totalAmount\":480001"),
                CREATED.replace("2026-11-13", "2026-11-12"),
                CREATED.replace("\"rooms\":1", "\"rooms\":\"1\""));
        for (String reply : replies) server.expect(requestTo(CREATE))
                .andRespond(withRawStatus(201).contentType(MediaType.APPLICATION_JSON).body(reply));
        for (String ignored : replies) assertEquals(Kind.UNKNOWN,
                assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST)).kind());
    }

    @Test
    void duplicateKeysTrailingJsonWrongContentTypeOrOversizedBodiesRemainUncertain() {
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(201).contentType(MediaType.APPLICATION_JSON)
                .body(CREATED.replace("\"status\":", "\"status\":\"FAILED\",\"status\":")));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(201).contentType(MediaType.APPLICATION_JSON).body(CREATED + "{}"));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(201).contentType(MediaType.TEXT_PLAIN).body(CREATED));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(201).contentType(MediaType.APPLICATION_JSON)
                .body(" ".repeat(ReplacementSupplierClient.MAX_BODY_BYTES + 1)));
        for (int index = 0; index < 3; index++) assertEquals(Kind.UNKNOWN,
                assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST)).kind());
        assertEquals(Kind.RESPONSE_TOO_LARGE,
                assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST)).kind());
    }

    @Test
    void onlyAContractRejectionEstablishesFailureAndIdempotencyConflictNeverDoes() {
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(409).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(409, "PRICE_CHANGED").replace("\"traceId\"", "\"currentTotalAmount\":498000,\"currency\":\"KRW\",\"traceId\"")));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(409).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(409, "IDEMPOTENCY_KEY_REUSED")));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(401).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(401, "UNAUTHENTICATED_SERVICE")));
        server.expect(requestTo(CREATE)).andRespond(withRawStatus(503).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(503, "SUPPLIER_UNAVAILABLE")));
        var rejected = supplier.create(REQUEST);
        assertEquals("FAILED", rejected.status()); assertEquals("PRICE_CHANGED", rejected.failureCode());
        assertEquals(498000L, rejected.currentAmount()); assertNull(rejected.confirmedAmount());
        assertNull(rejected.failedAt(), "API-029 ProblemDetail supplies no event timestamp");
        var uncertain = assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST));
        assertEquals(Kind.UNKNOWN, uncertain.kind()); assertEquals("IDEMPOTENCY_KEY_REUSED", uncertain.code());
        assertEquals(Kind.UNKNOWN, assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST)).kind());
        assertEquals(Kind.UNKNOWN, assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST)).kind());
    }

    @Test
    void onlyVerifiedLookupNotFoundPermitsTheWorkerToConsiderASameKeyRetry() {
        server.expect(requestTo(LOOKUP)).andRespond(withRawStatus(404).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(404, "BOOKING_REQUEST_NOT_FOUND")));
        server.expect(requestTo(LOOKUP)).andRespond(withRawStatus(404).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(404, "RESOURCE_NOT_FOUND")));
        server.expect(requestTo(LOOKUP)).andRespond(withRawStatus(503).contentType(MediaType.APPLICATION_PROBLEM_JSON)
                .body(problem(503, "SUPPLIER_UNAVAILABLE")));
        var absent = assertThrows(ReplacementSupplierException.class, () -> supplier.lookup(REQUEST));
        assertEquals(Kind.REQUEST_NOT_FOUND, absent.kind()); assertEquals(404, absent.httpStatus());
        assertEquals(Kind.UNKNOWN, assertThrows(ReplacementSupplierException.class, () -> supplier.lookup(REQUEST)).kind());
        var unavailable = assertThrows(ReplacementSupplierException.class, () -> supplier.lookup(REQUEST));
        assertEquals(Kind.UNKNOWN, unavailable.kind()); assertNull(unavailable.getCause());
        assertFalse(unavailable.getMessage().contains("private-detail")); assertFalse(unavailable.getMessage().contains(TOKEN));
    }

    @Test
    void processingAndConfirmedFailureKeepNullSuccessFieldsAndImmutableFailureTime() {
        server.expect(requestTo(LOOKUP)).andRespond(withSuccess(PROCESSING, MediaType.APPLICATION_JSON));
        server.expect(requestTo(LOOKUP)).andRespond(withSuccess(FAILED, MediaType.APPLICATION_JSON));
        server.expect(requestTo(LOOKUP)).andRespond(withSuccess(FAILED.replace(
                "\"failedAt\":\"2026-11-09T10:22:00+09:00\"", "\"failedAt\":null"), MediaType.APPLICATION_JSON));
        assertEquals("PROCESSING", supplier.lookup(REQUEST).status());
        var failed = supplier.lookup(REQUEST);
        assertEquals("FAILED", failed.status()); assertEquals("PRICE_CHANGED", failed.failureCode());
        assertEquals(498000L, failed.currentAmount()); assertEquals(OffsetDateTime.parse("2026-11-09T10:22:00+09:00"), failed.failedAt());
        assertEquals(Kind.UNKNOWN, assertThrows(ReplacementSupplierException.class, () -> supplier.lookup(REQUEST)).kind());
    }

    @Test
    void transportTimeoutDoesNotEstablishThatTheBookingFailed() {
        server.expect(requestTo(CREATE)).andRespond(withException(new SocketTimeoutException("private-detail")));
        var uncertain = assertThrows(ReplacementSupplierException.class, () -> supplier.create(REQUEST));
        assertEquals(Kind.TIMEOUT, uncertain.kind()); assertNull(uncertain.getCause());
        assertFalse(uncertain.getMessage().contains("private-detail"));
    }

    @Test
    void missingCredentialInvalidIdentityAndActiveTransactionCannotStartHttp() {
        assertEquals(Kind.NO_SERVICE_TOKEN, assertThrows(ReplacementSupplierException.class,
                () -> new ReplacementSupplierClient(http, " ").create(REQUEST)).kind());
        var malformed = new FrozenRequest("BRQ-001/other", REQUEST.quoteId(), REQUEST.propertyId(), REQUEST.stay(),
                REQUEST.expectedAmount(), REQUEST.currency(), REQUEST.guestReference());
        assertEquals(Kind.INVALID_REQUEST, assertThrows(ReplacementSupplierException.class, () -> supplier.create(malformed)).kind());
        TransactionSynchronizationManager.setActualTransactionActive(true);
        assertEquals(Kind.TRANSACTION_ACTIVE, assertThrows(ReplacementSupplierException.class, () -> supplier.lookup(REQUEST)).kind());
    }

    private static String problem(int status, String code) {
        return "{\"type\":\"about:blank\",\"status\":" + status
                + ",\"title\":\"Error\",\"detail\":\"private-detail\",\"code\":\"" + code + "\",\"traceId\":\"req-test\"}";
    }
}
