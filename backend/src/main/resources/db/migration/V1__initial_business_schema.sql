CREATE TABLE cases (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  case_code varchar(40) NOT NULL,
  booking_id bigint NOT NULL,
  status varchar(20) NOT NULL DEFAULT 'OPEN',
  priority varchar(20) NOT NULL DEFAULT 'NORMAL',
  assignee_id bigint,
  version bigint NOT NULL DEFAULT 0,
  close_reason varchar(80),
  closed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_cases_1 UNIQUE (case_code),
  CONSTRAINT uq_cases_2 UNIQUE (id, booking_id),
  CONSTRAINT ck_cases_1 CHECK (status IN ('OPEN','IN_PROGRESS','WAITING','CLOSED')),
  CONSTRAINT ck_cases_2 CHECK (priority IN ('NORMAL','URGENT')),
  CONSTRAINT ck_cases_3 CHECK (version >= 0),
  CONSTRAINT ck_cases_4 CHECK ((status='CLOSED') = (closed_at IS NOT NULL)),
  CONSTRAINT ck_cases_5 CHECK (status <> 'CLOSED' OR close_reason IS NOT NULL)
);

CREATE TABLE case_tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  case_id bigint NOT NULL,
  task_type varchar(40) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'TODO',
  assignee_id bigint,
  due_at timestamptz,
  completed_at timestamptz,
  completion_evidence_id bigint,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  is_required boolean NOT NULL DEFAULT true,
  booking_id bigint NOT NULL,
  completion_note text,
  PRIMARY KEY (id),
  CONSTRAINT ck_case_tasks_1 CHECK (status IN ('TODO','IN_PROGRESS','DONE')),
  CONSTRAINT ck_case_tasks_2 CHECK ((status='DONE') = (completed_at IS NOT NULL)),
  CONSTRAINT ck_case_tasks_3 CHECK (status <> 'DONE' OR completion_evidence_id IS NOT NULL OR NULLIF(btrim(completion_note),'') IS NOT NULL)
);

CREATE TABLE incident_reports (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  report_code varchar(40) NOT NULL,
