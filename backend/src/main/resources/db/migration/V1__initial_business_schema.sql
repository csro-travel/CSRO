  supporting_text text,
  reviewed_by bigint,
  reviewed_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_evidence_nights_1 UNIQUE (evidence_id, booking_night_id),
  CONSTRAINT uq_evidence_nights_2 UNIQUE (id, booking_night_id),
