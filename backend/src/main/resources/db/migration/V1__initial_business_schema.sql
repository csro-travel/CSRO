CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  subject_key varchar(120) NOT NULL,
  display_name varchar(80) NOT NULL,
  role varchar(20) NOT NULL,
  is_active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_users_1 UNIQUE (subject_key),
  CONSTRAINT ck_users_1 CHECK (role IN ('CUSTOMER','COUNSELOR'))
);

CREATE TABLE hotels (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  hotel_code varchar(40) NOT NULL,
  name varchar(160) NOT NULL,
  time_zone varchar(60) NOT NULL DEFAULT 'Asia/Seoul',
  latitude numeric(9,6),
  longitude numeric(9,6),
  data_source varchar(30) NOT NULL DEFAULT 'SIMULATED',
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_hotels_1 UNIQUE (hotel_code),
  CONSTRAINT ck_hotels_1 CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_hotels_2 CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180),
  CONSTRAINT ck_hotels_3 CHECK ((latitude IS NULL) = (longitude IS NULL))
);

CREATE TABLE bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  booking_code varchar(40) NOT NULL,
  customer_id bigint NOT NULL,
  hotel_id bigint NOT NULL,
  supplier_code varchar(40) NOT NULL DEFAULT 'MOCK_SUPPLIER',
  supplier_booking_id varchar(80) NOT NULL,
  supplier_status varchar(24) NOT NULL DEFAULT 'CONFIRMED',
  check_in_date date NOT NULL,
  check_out_date date NOT NULL,
  adults smallint NOT NULL,
  rooms smallint NOT NULL DEFAULT 1,
  original_total_amount bigint NOT NULL,
  currency char(3) NOT NULL DEFAULT 'KRW',
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_bookings_1 UNIQUE (supplier_code, supplier_booking_id),
  CONSTRAINT uq_bookings_2 UNIQUE (booking_code),
  CONSTRAINT uq_bookings_3 UNIQUE (id, customer_id),
  CONSTRAINT ck_bookings_1 CHECK (check_out_date > check_in_date),
  CONSTRAINT ck_bookings_2 CHECK (adults > 0),
  CONSTRAINT ck_bookings_3 CHECK (rooms > 0),
  CONSTRAINT ck_bookings_4 CHECK (original_total_amount >= 0),
  CONSTRAINT ck_bookings_5 CHECK (supplier_status IN ('CONFIRMED','CANCELLED','CHANGED','UNKNOWN')),
  CONSTRAINT ck_bookings_6 CHECK (currency = 'KRW')
);

CREATE TABLE booking_nights (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  booking_id bigint NOT NULL,
  stay_date date NOT NULL,
  fulfillment_status varchar(20) NOT NULL DEFAULT 'UNKNOWN',
  fact_status varchar(24) NOT NULL DEFAULT 'UNCONFIRMED',
  accepted_assertion_id bigint,
  updated_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_booking_nights_1 UNIQUE (booking_id, stay_date),
  CONSTRAINT uq_booking_nights_2 UNIQUE (id, booking_id),
  CONSTRAINT ck_booking_nights_1 CHECK (fulfillment_status IN ('UNKNOWN','AVAILABLE','UNAVAILABLE')),
  CONSTRAINT ck_booking_nights_2 CHECK (fact_status IN ('UNCONFIRMED','VERIFIED','CONFLICT')),
  CONSTRAINT ck_booking_nights_3 CHECK (fact_status <> 'VERIFIED' OR fulfillment_status <> 'UNKNOWN'),
  CONSTRAINT ck_booking_nights_4 CHECK (fact_status <> 'VERIFIED' OR accepted_assertion_id IS NOT NULL),
  CONSTRAINT ck_booking_nights_5 CHECK ((fact_status = 'UNCONFIRMED' AND fulfillment_status = 'UNKNOWN' AND accepted_assertion_id IS NULL) OR (fact_status = 'VERIFIED' AND fulfillment_status IN ('AVAILABLE','UNAVAILABLE') AND accepted_assertion_id IS NOT NULL) OR (fact_status = 'CONFLICT' AND ((fulfillment_status = 'UNKNOWN' AND accepted_assertion_id IS NULL) OR (fulfillment_status IN ('AVAILABLE','UNAVAILABLE') AND accepted_assertion_id IS NOT NULL))))
);

CREATE TABLE risk_assessments (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  hotel_id bigint NOT NULL,
  target_check_in_date date NOT NULL,
  as_of timestamptz NOT NULL,
  risk_score numeric(5,4) NOT NULL,
  model_version varchar(80) NOT NULL,
  feature_set_version varchar(80) NOT NULL,
  feature_snapshot jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT ck_risk_assessments_1 CHECK (risk_score BETWEEN 0 AND 1)
);

CREATE TABLE jobs (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  job_code varchar(60) NOT NULL,
  booking_id bigint NOT NULL,
  case_id bigint,
  risk_assessment_id bigint,
  kind varchar(24) NOT NULL,
  trigger_type varchar(32) NOT NULL,
  status varchar(24) NOT NULL DEFAULT 'PENDING',
  parameters jsonb NOT NULL,
  attempt_count smallint NOT NULL DEFAULT 0,
  deadline_at timestamptz,
  next_attempt_at timestamptz,
  finished_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  result_payload jsonb,
  PRIMARY KEY (id),
  CONSTRAINT uq_jobs_1 UNIQUE (job_code),
  CONSTRAINT uq_jobs_2 UNIQUE (id, booking_id),
  CONSTRAINT uq_jobs_3 UNIQUE (id, case_id),
  CONSTRAINT ck_jobs_1 CHECK (kind IN ('RECHECK','QUOTE_SEARCH')),
  CONSTRAINT ck_jobs_2 CHECK (status IN ('PENDING','RUNNING','WAITING','COMPLETED','FAILED')),
  CONSTRAINT ck_jobs_3 CHECK (attempt_count >= 0),
  CONSTRAINT ck_jobs_4 CHECK (kind <> 'QUOTE_SEARCH' OR case_id IS NOT NULL)
);

CREATE TABLE evidence_records (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  booking_id bigint NOT NULL,
  job_id bigint,
  source_type varchar(32) NOT NULL,
  provider_code varchar(50),
  provider_event_id varchar(120),
  source_authenticated boolean NOT NULL DEFAULT false,
  raw_text text,
  raw_payload jsonb,
  occurred_at timestamptz,
  received_at timestamptz NOT NULL,
  payload_hash char(64),
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_evidence_records_1 UNIQUE (id, booking_id),
  CONSTRAINT ck_evidence_records_1 CHECK (source_type IN ('SUPPLIER_API','HOTEL_API','SUPPLIER_EVENT','HOTEL_EVENT','MANUAL_HOTEL')),
  CONSTRAINT ck_evidence_records_2 CHECK (raw_text IS NOT NULL OR raw_payload IS NOT NULL),
  CONSTRAINT ck_evidence_records_3 CHECK (source_type NOT IN ('SUPPLIER_EVENT','HOTEL_EVENT') OR (provider_code IS NOT NULL AND provider_event_id IS NOT NULL)),
  CONSTRAINT ck_evidence_records_4 CHECK (provider_event_id IS NULL OR provider_code IS NOT NULL)
);

CREATE TABLE agent_analyses (
