  CONSTRAINT ck_evidence_nights_2 CHECK (review_status IN ('PENDING_REVIEW','ACCEPTED','REJECTED')),
  CONSTRAINT ck_evidence_nights_3 CHECK ((review_status='PENDING_REVIEW' AND reviewed_at IS NULL) OR (review_status <> 'PENDING_REVIEW' AND reviewed_at IS NOT NULL))
