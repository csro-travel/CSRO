ALTER TABLE mock_quotes ADD CONSTRAINT fk_mock_quotes_1 FOREIGN KEY (product_id) REFERENCES mock_products (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
ALTER TABLE mock_booking_requests ADD CONSTRAINT fk_mock_booking_requests_1 FOREIGN KEY (quote_id) REFERENCES mock_quotes (id) ON DELETE RESTRICT ON UPDATE RESTRICT;
CREATE UNIQUE INDEX ix_mock_booking_requests_1 ON mock_booking_requests (quote_id) WHERE status='CONFIRMED';
