-- Mock supplier-owned PostgreSQL schema. Separate from Spring business Flyway.
-- Source: https://app.notion.com/p/99b2f2597c578398a54e816c1e8975d2

CREATE TABLE mock_products (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  property_code varchar(40) NOT NULL,
  property_name varchar(160) NOT NULL,
  room_type_code varchar(80) NOT NULL,
  room_name varchar(160) NOT NULL,
  rate_plan_code varchar(80) NOT NULL,
  max_adults smallint NOT NULL,
  breakfast_included boolean NOT NULL DEFAULT false,
  cancellation_policy varchar(40) NOT NULL,
  latitude numeric(9,6) NOT NULL,
  longitude numeric(9,6) NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_mock_products_1 UNIQUE (property_code, room_type_code),
  CONSTRAINT uq_mock_products_2 UNIQUE (property_code, rate_plan_code),
  CONSTRAINT ck_mock_products_1 CHECK (max_adults > 0),
  CONSTRAINT ck_mock_products_2 CHECK (latitude BETWEEN -90 AND 90),
  CONSTRAINT ck_mock_products_3 CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE mock_night_inventory (
  product_id bigint NOT NULL,
  stay_date date NOT NULL,
  available_rooms integer NOT NULL,
  base_amount bigint NOT NULL,
  mandatory_fees_amount bigint NOT NULL,
  PRIMARY KEY (product_id, stay_date),
  CONSTRAINT ck_mock_night_inventory_1 CHECK (available_rooms >= 0),
  CONSTRAINT ck_mock_night_inventory_2 CHECK (base_amount >= 0),
  CONSTRAINT ck_mock_night_inventory_3 CHECK (mandatory_fees_amount >= 0)
);

CREATE TABLE mock_quotes (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  quote_code varchar(80) NOT NULL,
  product_id bigint NOT NULL,
  check_in_date date NOT NULL,
  check_out_date date NOT NULL,
  adults smallint NOT NULL,
  rooms smallint NOT NULL,
  base_amount bigint NOT NULL,
  mandatory_fees_amount bigint NOT NULL,
  total_amount bigint NOT NULL,
  currency char(3) NOT NULL DEFAULT 'KRW',
  checked_at timestamptz NOT NULL,
  expires_at timestamptz NOT NULL,
  PRIMARY KEY (id),
  CONSTRAINT uq_mock_quotes_1 UNIQUE (quote_code),
  CONSTRAINT ck_mock_quotes_1 CHECK (check_out_date > check_in_date),
  CONSTRAINT ck_mock_quotes_2 CHECK (adults > 0),
  CONSTRAINT ck_mock_quotes_3 CHECK (rooms > 0),
  CONSTRAINT ck_mock_quotes_4 CHECK (base_amount >= 0),
  CONSTRAINT ck_mock_quotes_5 CHECK (mandatory_fees_amount >= 0),
  CONSTRAINT ck_mock_quotes_6 CHECK (total_amount = base_amount + mandatory_fees_amount),
  CONSTRAINT ck_mock_quotes_7 CHECK (currency = 'KRW'),
  CONSTRAINT ck_mock_quotes_8 CHECK (expires_at > checked_at)
);

CREATE TABLE mock_booking_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
  request_code varchar(100) NOT NULL,
  quote_id bigint NOT NULL,
  guest_reference varchar(80) NOT NULL,
  request_hash char(64) NOT NULL,
  expected_amount bigint NOT NULL,
  status varchar(20) NOT NULL,
  supplier_booking_id varchar(80),
  confirmed_amount bigint,
  http_status smallint NOT NULL,
  response_payload jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (id),
  CONSTRAINT uq_mock_booking_requests_1 UNIQUE (request_code),
  CONSTRAINT uq_mock_booking_requests_2 UNIQUE (supplier_booking_id),
  CONSTRAINT ck_mock_booking_requests_1 CHECK (expected_amount >= 0),
  CONSTRAINT ck_mock_booking_requests_2 CHECK (status IN ('CONFIRMED','FAILED')),
  CONSTRAINT ck_mock_booking_requests_3 CHECK ((status = 'CONFIRMED') = (supplier_booking_id IS NOT NULL AND confirmed_amount IS NOT NULL)),
  CONSTRAINT ck_mock_booking_requests_4 CHECK (status <> 'CONFIRMED' OR (confirmed_amount = expected_amount AND http_status = 201))
);

